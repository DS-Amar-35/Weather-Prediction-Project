# mcp_server.py
from fastmcp import FastMCP
import requests
import chromadb
from openpyxl import Workbook
from docx import Document
from pypdf import PdfReader
import os

mcp = FastMCP("Smart Assistant")

# --- CHROMADB SETUP ---
chroma_client = chromadb.PersistentClient(path="./chroma_db")
collection = chroma_client.get_or_create_collection("docs")

# --- TOOL 1: WEATHER API ---
@mcp.tool()
def get_weather(city: str) -> str:
    """Get live weather for any city. Input: city name like Hyderabad"""
    try:
        # 1. Get Latitude / Longitude
        geo_url = f"https://geocoding-api.open-meteo.com/v1/search?name={city}&count=1&language=en&format=json"
        geo = requests.get(geo_url).json()
        if "results" not in geo:
            return f"City {city} not found."
        lat = geo["results"][0]["latitude"]
        lon = geo["results"][0]["longitude"]
        name = geo["results"][0]["name"]

        # 2. Get Weather
        w_url = f"https://api.open-meteo.com/v1/forecast?latitude={lat}&longitude={lon}&current=temperature_2m,relative_humidity_2m,wind_speed_10m,weather_code"
        w = requests.get(w_url).json()
        cur = w["current"]
        return f"Weather in {name}: Temperature {cur['temperature_2m']}°C, Humidity {cur['relative_humidity_2m']}%, Wind {cur['wind_speed_10m']} km/h"
    except Exception as e:
        return f"Error: {str(e)}"

# --- TOOL 2: RAG - SEARCH DOCS ---
@mcp.tool()
def search_docs(query: str) -> str:
    """Search information from uploaded PDF documents. Use this for any PDF question."""
    try:
        results = collection.query(query_texts=[query], n_results=3)
        if not results["documents"] or not results["documents"][0]:
            return "No document found. Please upload PDF first."
        docs = "\n---\n".join(results["documents"][0])
        return f"Relevant content from PDF:\n{docs}"
    except Exception as e:
        return f"Error: {str(e)}"

# --- TOOL 3: EXCEL AUTOMATION ---
@mcp.tool()
def save_to_excel(city: str, temperature: str, humidity: str = "") -> str:
    """Save weather data to Excel file"""
    try:
        os.makedirs("outputs", exist_ok=True)
        wb = Workbook()
        ws = wb.active
        ws.title = "Weather"
        ws.append(["City", "Temperature", "Humidity"])
        ws.append([city, temperature, humidity])
        # Make header bold
        for cell in ws[1]:
            cell.font = cell.font.copy(bold=True)
        path = "outputs/weather_data.xlsx"
        wb.save(path)
        return f"Excel saved successfully at {path}. City: {city}, Temp: {temperature}"
    except Exception as e:
        return f"Error: {str(e)}"

# --- TOOL 4: WORD AUTOMATION ---
@mcp.tool()
def generate_word_report(city: str, summary: str) -> str:
    """Generate Word report for weather or document summary"""
    try:
        os.makedirs("outputs", exist_ok=True)
        doc = Document()
        doc.add_heading(f"Smart Assistant Report - {city}", 0)
        doc.add_paragraph(f"Generated by Smart Personal AI Assistant using Groq LLM.")
        doc.add_heading("Summary", level=1)
        doc.add_paragraph(summary)
        doc.add_heading("Details", level=1)
        doc.add_paragraph(f"City: {city}")
        doc.add_paragraph(f"Report generated automatically via MCP Tool.")
        path = "outputs/report.docx"
        doc.save(path)
        return f"Word report saved successfully at {path}"
    except Exception as e:
        return f"Error: {str(e)}"

# --- HELPER: LOAD PDF INTO CHROMADB ---
@mcp.tool()
def load_pdf_to_db(pdf_path: str) -> str:
    """Load PDF into ChromaDB for RAG. Call this after upload."""
    try:
        reader = PdfReader(pdf_path)
        full_text = ""
        for page in reader.pages:
            full_text += page.extract_text() or ""
        # Chunking - 500 chars each
        chunks = [full_text[i:i+500] for i in range(0, len(full_text), 500)]
        for i, chunk in enumerate(chunks):
            collection.add(documents=[chunk], ids=[f"{pdf_path}_{i}"])
        return f"Loaded {len(chunks)} chunks from {pdf_path} into ChromaDB"
    except Exception as e:
        return f"Error: {str(e)}"

if __name__ == "__main__":
    mcp.run()